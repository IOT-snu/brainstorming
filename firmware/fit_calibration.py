"""
Generate firmware/esp32_foa/foa_config.h: node settings, per-node HMAC keys and the fleet-shared
feature basis (standardisation constants and the 60 x 10 projection), exactly like
experiments/foa/data.Space does for N-BaIoT.

  python3 firmware/fit_calibration.py --placeholder
      Development header: random keys and a fixed orthonormal basis, so the sketch compiles and
      runs before any calibration data exists.

  python3 firmware/fit_calibration.py --from-logs node0.log node1.log node2.log node3.log
      Fit on clean traffic logged by each node with CALIB_LOG enabled (lines "RAW,<60 values>").
      Each node is centred on itself before the shared PCA, as in the simulations.

Keys are written into the header for the course testbed only. For any real deployment they must be
provisioned per device and never committed.
"""
import argparse, os, secrets
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "esp32_foa", "foa_config.h")
FEAT_N, D = 60, 16


def signlog(X):
    return np.sign(X) * np.log1p(np.abs(X))


def fit(logs, floor=0.05):
    T = []
    for p in logs:
        rows = [list(map(float, l.split(",")[1:])) for l in open(p) if l.startswith("RAW,")]
        X = np.array([r for r in rows if len(r) == FEAT_N])
        T.append(signlog(X))
    cent = np.vstack([t - t.mean(0) for t in T])
    mean = np.vstack(T).mean(0)
    std = np.maximum(cent.std(0), floor)
    Vt = np.linalg.svd(cent / std - (cent / std).mean(0), full_matrices=False)[2]
    return mean, std, Vt[:D].T


def lit(v):
    s = f"{v:.7g}"
    return (s if any(c in s for c in ".e") else s + ".0") + "f"


def arr(name, a, per=10):
    vals = [lit(v) for v in np.asarray(a).ravel()]
    lines = [", ".join(vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const float {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--placeholder", action="store_true")
    g.add_argument("--from-logs", nargs="+")
    ap.add_argument("--nodes", type=int, default=4)
    a = ap.parse_args()
    if a.placeholder:
        mean, std = np.zeros(FEAT_N), np.ones(FEAT_N)
        W = np.linalg.qr(np.random.default_rng(0).normal(size=(FEAT_N, D)))[0]
        keys = [bytes(np.random.default_rng(100 + k).integers(0, 256, 32, dtype=np.uint8)) for k in range(a.nodes)]
        note = "PLACEHOLDER basis and DEVELOPMENT keys: regenerate with --from-logs before measuring."
    else:
        mean, std, W = fit(a.from_logs)
        keys = [secrets.token_bytes(32) for _ in range(a.nodes)]
        note = f"Fitted on {len(a.from_logs)} node logs. Keys are fresh random keys for this testbed."
    key_rows = ",\n    ".join("{" + ", ".join(f"0x{b:02x}" for b in k) + "}" for k in keys)
    h = f"""/* Generated by firmware/fit_calibration.py. {note} */
#ifndef FOA_CONFIG_H
#define FOA_CONFIG_H

#include <stdint.h>
#include "foa_features.h"

#ifndef NODE_ID
#define NODE_ID 0                 /* set per board: arduino-cli ... --build-property build.extra_flags=-DNODE_ID=1 */
#endif
#define N_NODES {a.nodes}
#define WIFI_CHANNEL 6            /* router fixed to this channel so ESP-NOW and Wi-Fi share it */
#define WIFI_SSID "your-ssid"
#define WIFI_PASS "your-password"
#define COLLECTOR_IP 192, 168, 1, 100
#define COLLECTOR_PORT 5005       /* laptop: telemetry sink and node log collector */
#define NODE_PORT 5006            /* node listens here; the laptop poisoner sends here */
#define BATCH 200                 /* feature vectors per learning cycle, as in the simulations */
#define SAMPLE_MS 50              /* one feature vector every 50 ms: a 10 s cycle */
#define TX_PERIOD_MS 200          /* telemetry period */
#define CAL_CYCLES 6              /* clean cycles used for on-device calibration */
#define GOSSIP_WAIT_MS 300        /* how long a node waits for peer frames each cycle */

static const uint8_t FOA_KEYS[N_NODES][32] = {{
    {key_rows}
}};

{arr("FEAT_MEAN", mean)}
{arr("FEAT_STD", std)}
{arr("FEAT_W", W)}
#endif
"""
    open(OUT, "w").write(h)
    print("wrote", OUT, "-", note)


if __name__ == "__main__":
    main()
